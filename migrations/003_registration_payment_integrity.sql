ALTER TABLE payments ALTER COLUMN order_id DROP NOT NULL;

ALTER TABLE payments
  ADD COLUMN IF NOT EXISTS refund_id TEXT,
  ADD COLUMN IF NOT EXISTS refund_amount_paise INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS refunded_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS team_members (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id INTEGER NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  position        INTEGER NOT NULL CHECK (position > 0),
  full_name       TEXT NOT NULL,
  email           TEXT,
  phone           TEXT,
  college         TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (registration_id, position)
);

INSERT INTO team_members (registration_id, position, full_name)
SELECT r.id, member.ordinality::INTEGER, member.full_name
FROM registrations r
CROSS JOIN LATERAL jsonb_array_elements_text(r.members::JSONB)
  WITH ORDINALITY AS member(full_name, ordinality)
WHERE r.plan = 'team'
  AND r.members IS NOT NULL
  AND jsonb_typeof(r.members::JSONB) = 'array'
ON CONFLICT (registration_id, position) DO NOTHING;

INSERT INTO payments (
  registration_id,
  order_id,
  payment_id,
  amount_paise,
  currency,
  status,
  verification_status,
  paid_at,
  created_at,
  updated_at
)
SELECT
  r.id,
  r.order_id,
  r.payment_id,
  r.amount_paise,
  'INR',
  CASE WHEN r.status = 'paid' THEN 'paid'
       WHEN r.status = 'failed' THEN 'failed'
       WHEN r.status = 'refunded' THEN 'refunded'
       ELSE 'pending' END,
  CASE WHEN r.status IN ('paid', 'refunded') THEN 'verified'
       WHEN r.status = 'failed' THEN 'failed'
       ELSE 'unverified' END,
  r.paid_at,
  r.created_at,
  NOW()
FROM registrations r
WHERE NOT EXISTS (
  SELECT 1 FROM payments p WHERE p.registration_id = r.id
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pay_payment_id_unique
  ON payments(payment_id)
  WHERE payment_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_pay_refund_id_unique
  ON payments(refund_id)
  WHERE refund_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS payment_refunds (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_record_id INTEGER NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
  refund_id         TEXT NOT NULL UNIQUE,
  amount_paise      INTEGER NOT NULL CHECK (amount_paise > 0),
  currency          TEXT NOT NULL DEFAULT 'INR',
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS webhook_events (
  event_id     TEXT PRIMARY KEY,
  event_type   TEXT NOT NULL,
  received_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processed_at TIMESTAMPTZ,
  outcome      TEXT
);
