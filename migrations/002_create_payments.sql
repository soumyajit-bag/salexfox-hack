-- Add member_count to registrations if not present
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS member_count INTEGER DEFAULT 1;

-- Create payments table to track every payment attempt and status
CREATE TABLE IF NOT EXISTS payments (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id     INTEGER NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  order_id            TEXT NOT NULL,
  payment_id          TEXT,
  amount_paise        INTEGER NOT NULL,
  currency            TEXT NOT NULL DEFAULT 'INR',
  status              TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed', 'refunded')),
  verification_status TEXT NOT NULL DEFAULT 'unverified' CHECK (verification_status IN ('unverified', 'verified', 'failed')),
  failure_reason      TEXT,
  error_code          TEXT,
  error_description   TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at             TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_pay_reg_id ON payments(registration_id);
CREATE INDEX IF NOT EXISTS idx_pay_order_id ON payments(order_id);
CREATE INDEX IF NOT EXISTS idx_pay_payment_id ON payments(payment_id);
CREATE INDEX IF NOT EXISTS idx_pay_status ON payments(status);
